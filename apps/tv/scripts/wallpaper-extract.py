#!/usr/bin/env python3
"""Copy the painting half of the desktop preview into the launcher's wallpaper asset.

    scripts/wallpaper-extract.py

Reads  tv-preview/assets/private/desktop-hp.html  (scene + mocked menu bar and dock)
Writes jarvis-tv/app/src/private/assets/wallpaper/scene.html  (scene only)
Both are git-ignored; see jarvis-tv/app/src/private/README.md.
"""
from pathlib import Path

here = Path(__file__).resolve().parent.parent
src = (here / "tv-preview/assets/private/desktop-hp.html").read_text()
out = here / "jarvis-tv/app/src/private/assets/wallpaper/scene.html"

i = src.index("<script>") + len("<script>")
j = src.index("/* ════════════════════════════════════════════════════════════════════════════\n   Menu bar and dock")
js = src[i:j]
js = js.replace("getContext('2d');", "getContext('2d', { willReadFrequently: true });", 1)
js = js.replace("if (now - last > 1000 / 24)", "if (now - last > 1000 / FPS)")
js = js.replace("let snowing = false;\n", "")
assert "FPS" in js, "frame loop not found"

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("""<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,user-scalable=no">
<!-- Generated by scripts/wallpaper-extract.py from tv-preview/assets/private/desktop-hp.html. -->
<style>
  html, body { margin: 0; height: 100%; overflow: hidden; background: #151a42; }
  #px { position: fixed; inset: 0; width: 100vw; height: 100vh; image-rendering: pixelated; }
  .vignette { position: fixed; inset: 0; pointer-events: none; background: radial-gradient(120% 90% at 55% 40%, transparent 55%, rgba(20,10,30,.28)); }
</style></head>
<body><canvas id="px" width="480" height="270"></canvas><div class="vignette"></div>
<script>
const FPS = +(new URLSearchParams(location.search).get('fps') || 20);
let snowing = new URLSearchParams(location.search).get('snow') === '1';
""" + js + "</script></body></html>\n")
print(f"wrote {out.relative_to(here)} ({out.stat().st_size} bytes)")
